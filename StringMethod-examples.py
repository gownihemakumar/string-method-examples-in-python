
print("========string methods==========")
name="SRI venkateswara UNIVERSITY"
print("UPPER CASE:",name.upper())#returns upper letters
print("lower case:",name.lower())#returns lower letters
print("Title:",name.title())#every word first letter is capital
print("casefold:",name.casefold())#string into lower case
print("Capitalize:",name.capitalize())#converts first letter into capital
print("replace:",name.replace("UNIVERSITY","UNIVERSITY COLLEGE OF ENGINEERING"))
#replaces a word or letter in a string
print("count:",name.count("S"))#counting how many characters are there
print("swapcase:",name.swapcase())#convert upper letter to upper and upper to lower cases
print("split:",name.split(" "))#spliting into words
